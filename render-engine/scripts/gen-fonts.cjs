// Generates src/fonts.ts: static @fontsource imports (latin subset, every upright weight each family
// ships) for SUPPORTED_FONTS, matching frontend/styles/fonts.ts so preview == render.
// 'Courier New' is a Windows system font and has no package. Italic is synthesized by Chromium.
// Run: npm run gen:fonts   (re-run when SUPPORTED_FONTS in frontend/lib/constants.ts changes)
const fs = require('node:fs')
const path = require('node:path')

const FAMILIES = [
  'Montserrat', 'Inter', 'Poppins', 'Orbitron', 'Outfit', 'Roboto', 'Oswald', 'Plus Jakarta Sans',
  'Fredoka', 'Exo 2', 'Bebas Neue', 'Anton', 'Bangers', 'Permanent Marker', 'Righteous', 'Russo One',
  'Lilita One',
]

const root = path.resolve(__dirname, '..')
const imports = []
const weights = {}
for (const family of FAMILIES) {
  const pkg = family.toLowerCase().replace(/ /g, '-')
  const dir = path.join(root, 'node_modules', '@fontsource', pkg)
  if (!fs.existsSync(dir)) throw new Error(`@fontsource/${pkg} is not installed`)
  const ws = fs
    .readdirSync(dir)
    .map((f) => /^latin-(\d{3})\.css$/.exec(f))
    .filter(Boolean)
    .map((m) => Number(m[1]))
    .sort((a, b) => a - b)
  if (!ws.length) throw new Error(`no latin weights in @fontsource/${pkg}`)
  weights[family] = ws
  for (const w of ws) imports.push(`import '@fontsource/${pkg}/latin-${w}.css'`)
}

const out = `// GENERATED by scripts/gen-fonts.cjs — do not edit by hand.
// Offline fonts for the render bundle (no Google Fonts). Mirrors frontend/styles/fonts.ts.
${imports.join('\n')}

/** Upright weights bundled per family. Families not listed (e.g. 'Courier New') are system fonts. */
export const FONT_WEIGHTS: Record<string, number[]> = ${JSON.stringify(weights, null, 2)}
`
fs.writeFileSync(path.join(root, 'src', 'fonts.ts'), out.replace(/\r?\n/g, '\n'))
console.log(`src/fonts.ts: ${FAMILIES.length} families, ${imports.length} faces`)
